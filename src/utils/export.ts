export async function exportAsPDF(metadata: ImageMetadata): Promise<void> {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF()
  let y = 20

  doc.setFontSize(18)
  doc.text('Image Metadata Report', 14, y)
  y += 12

  doc.setFontSize(11)
  doc.text(`File: ${metadata.file.file_name}`, 14, y)
  y += 10

  // File Info
  doc.setFontSize(14)
  doc.text('File Info', 14, y)
  y += 8
  doc.setFontSize(10)

  const fileRows = [
    ['File Name', metadata.file.file_name],
    ['File Size', metadata.file.file_size_formatted],
    ['MD5 Checksum', metadata.file.md5_checksum],
    ['MIME Type', metadata.file.mime_type],
    ['File Type', metadata.file.file_type],
  ]

  fileRows.forEach(([label, value]) => {
    doc.text(`${label}:`, 14, y)
    doc.text(value, 70, y, { maxWidth: 130 })
    y += 7
  })

  y += 5

  // Image Info
  doc.setFontSize(14)
  doc.text('Image Info', 14, y)
  y += 8
  doc.setFontSize(10)

  const imgRows: [string, string][] = [
    ['Dimensions', `${metadata.image.image_width} x ${metadata.image.image_height}`],
    ['Megapixels', `${metadata.image.megapixels} MP`],
    ['Bit Depth', String(metadata.image.bit_depth)],
    ['Color Type', metadata.image.color_type],
  ]
  if (metadata.image.compression) imgRows.push(['Compression', metadata.image.compression])
  if (metadata.image.interlace) imgRows.push(['Interlace', metadata.image.interlace])

  imgRows.forEach(([label, value]) => {
    doc.text(`${label}:`, 14, y)
    doc.text(value, 70, y)
    y += 7
  })

  // Simple page break check
  if (y > 250 && metadata.exif && metadata.exif.length > 0) {
    doc.addPage()
    y = 20
  }

  // EXIF
  if (metadata.exif && metadata.exif.length > 0) {
    y += 5
    doc.setFontSize(14)
    doc.text(`EXIF Data (${metadata.exif.length} items)`, 14, y)
    y += 8
    doc.setFontSize(9)

    metadata.exif.forEach((entry) => {
      if (y > 280) {
        doc.addPage()
        y = 20
      }
      doc.text(`${entry.tag_name}:`, 14, y)
      doc.text(entry.value, 75, y, { maxWidth: 120 })
      y += 6
    })
  }

  doc.save(getSafeFileName(metadata, 'pdf'))
}
