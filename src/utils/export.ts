import type { ImageMetadata, ExifEntry } from '../types/metadata'

function downloadBlob(content: string | Uint8Array, fileName: string, mimeType: string): void {
  const blob = content instanceof Uint8Array
    ? new Blob([content as BlobPart], { type: mimeType })
    : new Blob([content], { type: `${mimeType};charset=utf-8` })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = fileName
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

function getSafeFileName(metadata: ImageMetadata, ext: string): string {
  const base = metadata.file.file_name.replace(/\.[^.]+$/, '')
  return `${base}_metadata.${ext}`
}

export function exportAsJSON(metadata: ImageMetadata): void {
  const json = JSON.stringify(metadata, null, 2)
  downloadBlob(json, getSafeFileName(metadata, 'json'), 'application/json')
}

export function exportAsCSV(metadata: ImageMetadata): void {
  const rows: [string, string][] = []

  // File info
  rows.push(['=== 文件信息 ===', ''])
  rows.push(['file_name', metadata.file.file_name])
  rows.push(['file_size', metadata.file.file_size_formatted])
  rows.push(['md5_checksum', metadata.file.md5_checksum])
  rows.push(['mime_type', metadata.file.mime_type])
  rows.push(['file_type', metadata.file.file_type])
  rows.push(['file_type_extension', metadata.file.file_type_extension])

  // Image info
  rows.push(['=== 图片信息 ===', ''])
  rows.push(['image_width', String(metadata.image.image_width)])
  rows.push(['image_height', String(metadata.image.image_height)])
  rows.push(['image_size', metadata.image.image_size])
  rows.push(['megapixels', `${metadata.image.megapixels} MP`])
  rows.push(['bit_depth', String(metadata.image.bit_depth)])
  rows.push(['color_type', metadata.image.color_type])

  if (metadata.image.compression) {
    rows.push(['compression', metadata.image.compression])
  }
  if (metadata.image.filter) {
    rows.push(['filter', metadata.image.filter])
  }
  if (metadata.image.interlace) {
    rows.push(['interlace', metadata.image.interlace])
  }

  // EXIF
  if (metadata.exif && metadata.exif.length > 0) {
    rows.push(['=== EXIF 数据 ===', ''])
    metadata.exif.forEach((e: ExifEntry) => {
      rows.push([e.tag_name, e.value])
    })
  }

  const csv = rows.map(r => `"${r[0].replace(/"/g, '""')}","${r[1].replace(/"/g, '""')}"`).join('\n')
  downloadBlob('﻿' + csv, getSafeFileName(metadata, 'csv'), 'text/csv')
}

export function exportAsTXT(metadata: ImageMetadata): void {
  const lines: string[] = []
  const sep = '='.repeat(60)

  lines.push(sep)
  lines.push('  IMAGE METADATA REPORT')
  lines.push(sep)
  lines.push('')

  lines.push('--- FILE INFO ---')
  lines.push(`  file_name:            ${metadata.file.file_name}`)
  lines.push(`  file_size:            ${metadata.file.file_size_formatted}`)
  lines.push(`  md5_checksum:         ${metadata.file.md5_checksum}`)
  lines.push(`  mime_type:            ${metadata.file.mime_type}`)
  lines.push(`  file_type:            ${metadata.file.file_type}`)
  lines.push('')

  lines.push('--- IMAGE INFO ---')
  lines.push(`  image_width:          ${metadata.image.image_width}`)
  lines.push(`  image_height:         ${metadata.image.image_height}`)
  lines.push(`  image_size:           ${metadata.image.image_size}`)
  lines.push(`  megapixels:           ${metadata.image.megapixels} MP`)
  lines.push(`  bit_depth:            ${metadata.image.bit_depth}`)
  lines.push(`  color_type:           ${metadata.image.color_type}`)
  if (metadata.image.compression) lines.push(`  compression:          ${metadata.image.compression}`)
  if (metadata.image.filter) lines.push(`  filter:               ${metadata.image.filter}`)
  if (metadata.image.interlace) lines.push(`  interlace:            ${metadata.image.interlace}`)
  lines.push('')

  if (metadata.exif && metadata.exif.length > 0) {
    lines.push('--- EXIF DATA ---')
    metadata.exif.forEach((e: ExifEntry) => {
      lines.push(`  ${e.tag_name}: ${e.value}`)
    })
    lines.push('')
  }

  if (metadata.png_chunks) {
    lines.push('--- PNG TEXT CHUNKS ---')
    metadata.png_chunks.t_ext_chunks.forEach(c => {
      lines.push(`  [tEXt] ${c.keyword}: ${c.text.substring(0, 200)}`)
    })
    metadata.png_chunks.ztxt_chunks.forEach(c => {
      lines.push(`  [zTXt] ${c.keyword}: ${c.text.substring(0, 200)}`)
    })
    metadata.png_chunks.itxt_chunks.forEach(c => {
      lines.push(`  [iTXt] ${c.keyword}: ${c.text.substring(0, 200)}`)
    })
    lines.push('')
  }

  lines.push(sep)
  lines.push('Generated by Image Metadata Viewer')

  downloadBlob(lines.join('\n'), getSafeFileName(metadata, 'txt'), 'text/plain')
}

